class ToolBenchDataLoader:
    """Loads OpenBMB ToolBench test data."""

    def __init__(self, toolbench_dir: Path):
        self.toolbench_dir = Path(toolbench_dir)

    def load_test_set(self, test_set: str, max_samples: int = -1) -> List[ToolBenchQuery]:
        """Load test queries for a given test set (G1, G2, G3)."""
        # Try different possible locations
        possible_paths = [
            self.toolbench_dir / "data" / "test_instruction" / f"{test_set}_instruction.json",
            self.toolbench_dir / "data" / "instruction" / f"{test_set}_query.json",
            self.toolbench_dir / "data_example" / "instruction" / f"{test_set}_query.json",
        ]

        query_file = None
        for path in possible_paths:
            if path.exists():
                query_file = path
                break

        if query_file is None:
            raise FileNotFoundError(
                f"Test set {test_set} not found. Tried:\n" +
                "\n".join(f"  - {p}" for p in possible_paths) +
                "\n\nPlease download the data from: https://drive.google.com/drive/folders/1TysbSWYpP8EioFu9xPJtpbJZMLLmwAmL"
            )

        logger.info(f"Loading queries from: {query_file}")

        with open(query_file, "r") as f:
            data = json.load(f)

        queries = []
        for i, item in enumerate(data):
            if max_samples > 0 and i >= max_samples:
                break

            queries.append(ToolBenchQuery(
                query_id=item.get("query_id", i),
                query=item["query"],
                api_list=item.get("api_list", []),
                relevant_apis=item.get("relevant APIs", []),
            ))

        return queries

    def load_tool_docs(self, api_list: List[Dict]) -> str:
        """Load documentation for the APIs in the query."""
        docs = []

        for api_info in api_list:
            tool_name = api_info.get("tool_name", "")
            api_name = api_info.get("api_name", "")
            category = api_info.get("category_name", "")

            doc = f"Tool: {tool_name}\n"
            doc += f"API: {api_name}\n"
            doc += f"Category: {category}\n"

            # Add additional info if available
            if "api_description" in api_info:
                doc += f"Description: {api_info['api_description']}\n"
            if "required_parameters" in api_info:
                doc += f"Required Parameters: {api_info['required_parameters']}\n"
            if "optional_parameters" in api_info:
                doc += f"Optional Parameters: {api_info['optional_parameters']}\n"
            if "method" in api_info:
                doc += f"Method: {api_info['method']}\n"

            docs.append(doc)

        return "\n---\n".join(docs)


