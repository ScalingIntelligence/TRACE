def main():
    parser = argparse.ArgumentParser(description="OpenBMB ToolBench Evaluation")

    # Data settings
    parser.add_argument("--test-set", type=str, default="G1", choices=TEST_SETS,
                        help="Test set to evaluate (G1=single-tool, G2=intra-category, G3=intra-collection)")
    parser.add_argument("--toolbench-dir", type=str, default=str(DEFAULT_TOOLBENCH_DIR),
                        help="Path to OpenBMB ToolBench repository")
    parser.add_argument("--num-samples", type=int, default=-1,
                        help="Number of test samples (-1 for all)")

    # vLLM settings
    parser.add_argument("--vllm-url", type=str, default=None,
                        help="URL of single vLLM server (used when --use-internal-vllm is not set)")
    parser.add_argument("--vllm-urls", type=str, nargs="+", default=None,
                        help="URLs of multiple vLLM servers for parallel evaluation (deterministic assignment)")
    parser.add_argument("--vllm-model", type=str, default="Qwen/Qwen3-4B-Instruct-2507",
                        help="Model name for tokenizer/internal vLLM")
    parser.add_argument("--use-internal-vllm", action="store_true",
                        help="Use internal vLLM instead of external server")
    parser.add_argument("--gpu-memory-utilization", type=float, default=0.9,
                        help="GPU memory utilization for internal vLLM")
    parser.add_argument("--tensor-parallel-size", type=int, default=1,
                        help="Tensor parallel size for internal vLLM")
    parser.add_argument("--max-concurrency", type=int, default=8,
                        help="Maximum concurrent requests for multi-server mode")

    # Determinism settings
    parser.add_argument("--seed", type=int, default=None,
                        help="Random seed for deterministic generation")

    # Generation settings
    parser.add_argument("--temperature", type=float, default=0.0,
                        help="Temperature for generation")
    parser.add_argument("--max-tokens", type=int, default=1024,
                        help="Max tokens for generation")

    # Output settings
    parser.add_argument("--output-dir", type=str, default="eval_results/openbmb_toolbench",
                        help="Output directory for results")
    parser.add_argument("--response-log", type=str, default=None,
                        help="Path to log detailed responses (JSONL format)")
    parser.add_argument("--run-id", type=str, default=None,
                        help="Run ID for distinguishing multiple runs (useful for determinism testing)")

    args = parser.parse_args()

    # Setup output directory
    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    # Load data
    logger.info(f"Loading OpenBMB ToolBench test set: {args.test_set}")
    data_loader = ToolBenchDataLoader(args.toolbench_dir)

    try:
        queries = data_loader.load_test_set(args.test_set, args.num_samples)
        logger.info(f"Loaded {len(queries)} queries")
    except FileNotFoundError as e:
        logger.error(str(e))
        sys.exit(1)

    # Determine which mode to use
    use_multi_server = args.vllm_urls is not None and len(args.vllm_urls) > 0

    # Initialize generator
    if args.use_internal_vllm:
        if not VLLM_AVAILABLE:
            logger.error("vLLM is not installed. Install with: pip install vllm")
            sys.exit(1)
        logger.info(f"Using internal vLLM with model: {args.vllm_model}")
        logger.info(f"Seed: {args.seed}, Temperature: {args.temperature}")
        generator = InternalVLLMGenerator(
            model_name=args.vllm_model,
            seed=args.seed,
            gpu_memory_utilization=args.gpu_memory_utilization,
            tensor_parallel_size=args.tensor_parallel_size,
        )
    elif use_multi_server:
        logger.info(f"Using multi-server mode with {len(args.vllm_urls)} servers:")
        for i, url in enumerate(args.vllm_urls):
            logger.info(f"  Server {i}: {url}")
        logger.info(f"Max concurrency: {args.max_concurrency}")
        logger.info(f"Seed: {args.seed} (deterministic server assignment: query_index % {len(args.vllm_urls)})")
        generator = MultiServerVLLMGenerator(
            server_urls=args.vllm_urls,
            model_name=args.vllm_model,
            seed=args.seed,
        )
    else:
        # Single server mode (default to localhost:8082 if not specified)
        server_url = args.vllm_url or "http://localhost:8082"
        logger.info(f"Connecting to vLLM server: {server_url}")
        generator = VLLMGenerator(
            server_url=server_url,
            model_name=args.vllm_model,
            seed=args.seed,
        )

    # Initialize evaluator
    evaluator = ToolBenchEvaluator()

    # Setup response log
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    model_name_safe = args.vllm_model.replace("/", "_")

    # Include run_id and seed in filename for determinism testing
    run_suffix = f"_seed{args.seed}" if args.seed is not None else ""
    run_suffix += f"_{args.run_id}" if args.run_id else ""

    response_log_file = args.response_log or str(
        output_dir / f"{args.test_set}_{model_name_safe}_{timestamp}{run_suffix}_responses.jsonl"
    )

    logger.info(f"Logging responses to: {response_log_file}")
    if args.seed is not None:
        logger.info(f"Using seed {args.seed} for deterministic generation")

    # Run evaluation
    if use_multi_server:
        # Multi-server parallel evaluation with deterministic assignment
        logger.info(f"Running parallel evaluation with {args.max_concurrency} concurrent requests...")

        # Prepare all tasks with their tool docs
        tasks = []
        for i, query in enumerate(queries):
            tool_docs = data_loader.load_tool_docs(query.api_list)
            tasks.append((i, query, tool_docs))

        # Results storage (will be sorted by query_index for determinism)
        results_by_index = {}

        with open(response_log_file, "w") as log_file:
            with ThreadPoolExecutor(max_workers=args.max_concurrency) as executor:
                # Submit all tasks
                futures = {
                    executor.submit(
                        generator.generate_single,
                        query_index,
                        query,
                        tool_docs,
                        args.temperature,
                        args.max_tokens,
                    ): (query_index, query, tool_docs)
                    for query_index, query, tool_docs in tasks
                }

                # Process completed tasks with progress bar
                with tqdm(total=len(futures), desc=f"Evaluating {args.test_set}") as pbar:
                    for future in as_completed(futures):
                        query_index, query, tool_docs = futures[future]
                        try:
                            result_index, response = future.result()
                            results_by_index[result_index] = (query, response)
                        except Exception as e:
                            logger.error(f"Task failed for query {query_index}: {e}")
                            results_by_index[query_index] = (query, f"# Task error: {e}")
                        pbar.update(1)

            # Process results in order (sorted by query_index for determinism)
            for query_index in sorted(results_by_index.keys()):
                query, response = results_by_index[query_index]

                # Evaluate
                result = evaluator.evaluate(query, response)

                # Log (in deterministic order)
                log_entry = {
                    "query_id": query.query_id,
                    "query": query.query,
                    "response": response,
                    "expected_apis": result["expected_apis"],
                    "extracted_calls": result["extracted_calls"],
                    "precision": result["precision"],
                    "recall": result["recall"],
                    "f1": result["f1"],
                    "server_index": query_index % len(args.vllm_urls),  # Track which server was used
                }
                log_file.write(json.dumps(log_entry) + "\n")
                log_file.flush()

    else:
        # Single server sequential evaluation
        with open(response_log_file, "w") as log_file:
            for query in tqdm(queries, desc=f"Evaluating {args.test_set}"):
                # Get tool documentation
                tool_docs = data_loader.load_tool_docs(query.api_list)

                # Generate response
                response = generator.generate(
                    query,
                    tool_docs,
                    temperature=args.temperature,
                    max_tokens=args.max_tokens,
                )

                # Evaluate
                result = evaluator.evaluate(query, response)

                # Log
                log_entry = {
                    "query_id": query.query_id,
                    "query": query.query,
                    "response": response,
                    "expected_apis": result["expected_apis"],
                    "extracted_calls": result["extracted_calls"],
                    "precision": result["precision"],
                    "recall": result["recall"],
                    "f1": result["f1"],
                }
                log_file.write(json.dumps(log_entry) + "\n")
                log_file.flush()

    # Aggregate results
    results = evaluator.aggregate_results()

    # Print results
    logger.info("\n" + "=" * 60)
    logger.info(f"RESULTS - OpenBMB ToolBench {args.test_set}")
    logger.info("=" * 60)
    for key, value in results.items():
        if isinstance(value, float):
            logger.info(f"  {key}: {value:.4f}")
        else:
            logger.info(f"  {key}: {value}")

    # Save results
    results_file = output_dir / f"{args.test_set}_{model_name_safe}_{timestamp}{run_suffix}.json"
    full_results = {
        "args": vars(args),
        "results": results,
        "timestamp": timestamp,
        "seed": args.seed,
        "run_id": args.run_id,
    }
    with open(results_file, "w") as f:
        json.dump(full_results, f, indent=2)

    logger.info(f"\nResults saved to: {results_file}")
    logger.info(f"Response log: {response_log_file}")

    # Determinism hint
    if args.seed is not None:
        logger.info(f"\n[Determinism Test] To verify determinism, run again with same --seed {args.seed} and compare response logs")
        if use_multi_server:
            logger.info(f"[Multi-Server] Queries were deterministically assigned to servers: query_index % {len(args.vllm_urls)}")
            logger.info(f"[Multi-Server] For best determinism, ensure each vLLM server is started with --max-num-seqs 1")

    return results


if __name__ == "__main__":
    main()
