class ToolBenchEvaluator:
    """Evaluates model responses on ToolBench."""

    def __init__(self):
        self.results = []

    def extract_tool_calls(self, response: str) -> List[Tuple[str, str]]:
        """Extract tool calls from model response.

        Returns list of (tool_name, api_name) tuples.
        """
        tool_calls = []

        # Pattern 1: Action: tool_name / api_name
        action_pattern = r"Action:\s*([^\n]+)"
        matches = re.findall(action_pattern, response, re.IGNORECASE)
        for match in matches:
            # Try to split tool_name/api_name
            parts = match.strip().split("/")
            if len(parts) >= 2:
                tool_calls.append((parts[0].strip(), parts[1].strip()))
            else:
                tool_calls.append((match.strip(), ""))

        # Pattern 2: Function call format
        func_pattern = r"(?:call|use|invoke)\s+(?:the\s+)?['\"]?(\w+)['\"]?\s+(?:api|tool|function)"
        matches = re.findall(func_pattern, response, re.IGNORECASE)
        for match in matches:
            tool_calls.append((match, ""))

        return tool_calls

    def evaluate(
        self,
        query: ToolBenchQuery,
        response: str,
    ) -> Dict[str, Any]:
        """Evaluate a single response."""
        result = {
            "query_id": query.query_id,
            "query": query.query,
            "response": response,
            "expected_apis": query.relevant_apis or [[api["tool_name"], api["api_name"]] for api in query.api_list],
            "extracted_calls": [],
            "correct_tools": 0,
            "total_expected": 0,
            "precision": 0.0,
            "recall": 0.0,
            "f1": 0.0,
        }

        # Extract tool calls from response
        extracted = self.extract_tool_calls(response)
        result["extracted_calls"] = extracted

        # Get expected tools
        expected_tools = set()
        for api in result["expected_apis"]:
            if isinstance(api, list) and len(api) >= 1:
                expected_tools.add(api[0].lower())  # Tool name
            elif isinstance(api, dict):
                expected_tools.add(api.get("tool_name", "").lower())

        # Get extracted tools
        extracted_tools = set(t[0].lower() for t in extracted if t[0])

        # Calculate metrics
        result["total_expected"] = len(expected_tools)
        result["correct_tools"] = len(expected_tools & extracted_tools)

        if extracted_tools:
            result["precision"] = result["correct_tools"] / len(extracted_tools)
        if expected_tools:
            result["recall"] = result["correct_tools"] / len(expected_tools)
        if result["precision"] + result["recall"] > 0:
            result["f1"] = 2 * result["precision"] * result["recall"] / (result["precision"] + result["recall"])

        self.results.append(result)
        return result

    def aggregate_results(self) -> Dict[str, float]:
        """Aggregate results across all evaluated queries."""
        if not self.results:
            return {}

        n_total = len(self.results)
        avg_precision = sum(r["precision"] for r in self.results) / n_total
        avg_recall = sum(r["recall"] for r in self.results) / n_total
        avg_f1 = sum(r["f1"] for r in self.results) / n_total

        # Pass rate: queries where at least one correct tool was called
        n_pass = sum(1 for r in self.results if r["correct_tools"] > 0)

        return {
            "total": n_total,
            "pass_count": n_pass,
            "pass_rate": n_pass / n_total,
            "avg_precision": avg_precision,
            "avg_recall": avg_recall,
            "avg_f1": avg_f1,
        }


