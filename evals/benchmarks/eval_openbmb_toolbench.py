@dataclass
class ToolBenchQuery:
    """A single ToolBench test query."""
    query_id: int
    query: str
    api_list: List[Dict[str, str]]  # List of {category_name, tool_name, api_name}
    relevant_apis: List[List[str]] = field(default_factory=list)  # [[tool_name, api_name], ...]


