#!/usr/bin/env python3
"""
OpenBMB ToolBench Evaluation with vLLM

This script evaluates LLMs on OpenBMB ToolBench benchmark using vLLM for inference.
OpenBMB ToolBench contains 16,000+ real-world APIs across various categories.

NOTE: Unlike tau-bench, ToolBench does NOT have a user LLM. The user queries are
static/pre-defined in the dataset, not generated by an LLM simulator.

Test sets:
- G1: Single-tool scenarios
- G2: Intra-category multi-tool scenarios
- G3: Intra-collection multi-tool scenarios

Usage:
    # With single external vLLM server:
    python eval_openbmb_toolbench.py \
        --test-set G1 \
        --vllm-url http://localhost:8082 \
        --num-samples 50

    # With multiple vLLM servers (deterministic parallel evaluation):
    python eval_openbmb_toolbench.py \
        --test-set G1 \
        --vllm-urls http://localhost:8080 http://localhost:8081 http://localhost:8082 \
        --max-concurrency 24 \
        --seed 42

    # With internal vLLM (no server needed):
    python eval_openbmb_toolbench.py \
        --test-set G1 \
        --use-internal-vllm \
        --vllm-model Qwen/Qwen3-4B-Instruct-2507 \
        --num-samples 10 \
        --seed 42

    # Determinism test (run twice with same seed):
    python eval_openbmb_toolbench.py --use-internal-vllm --seed 42 --num-samples 5 --run-id run1
    python eval_openbmb_toolbench.py --use-internal-vllm --seed 42 --num-samples 5 --run-id run2

References:
    - ToolBench: https://github.com/OpenBMB/ToolBench
    - Paper: "ToolLLM: Facilitating Large Language Models to Master 16000+ Real-world APIs"
"""

