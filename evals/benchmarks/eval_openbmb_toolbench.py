# Multi-Server vLLM Generator (Deterministic Parallel Evaluation)
# ============================================================================

class MultiServerVLLMGenerator:
    """
    Generates responses using multiple vLLM servers for parallel evaluation.

    Maintains determinism by:
    1. Deterministically assigning each query to a server based on query_index % num_servers
    2. Using the same seed for all requests
    3. Collecting results in original order (sorted by query_id)

    For best determinism, each vLLM server should be started with --max-num-seqs 1
    to ensure requests are processed one at a time on each server.
    """

    def __init__(
        self,
        server_urls: List[str],
        model_name: str = "Qwen/Qwen3-4B-Instruct-2507",
        timeout: float = 120.0,
        seed: Optional[int] = None,
    ):
        self.server_urls = []
        for url in server_urls:
            url = url.rstrip("/")
            if not url.endswith("/v1"):
                url = url + "/v1"
            self.server_urls.append(url)

        self.model_name = model_name
        self.timeout = timeout
        self.seed = seed
        self.num_servers = len(self.server_urls)

        # Thread-local sessions for each server
        self._local = threading.local()

        # Load tokenizer for prompt formatting (shared across threads)
        if TRANSFORMERS_AVAILABLE:
            self.tokenizer = AutoTokenizer.from_pretrained(model_name, trust_remote_code=True)
            if self.tokenizer.pad_token is None:
                self.tokenizer.pad_token = self.tokenizer.eos_token
        else:
            self.tokenizer = None

        # Verify servers and auto-detect model names
        self.server_models = {}
        for i, url in enumerate(self.server_urls):
            try:
                session = requests.Session()
                r = session.get(f"{url}/models", timeout=10)
                if r.status_code == 200:
                    models = r.json().get("data", [])
                    if models:
                        self.server_models[url] = models[0].get("id", model_name)
                        logger.info(f"Server {i} ({url}): model={self.server_models[url]}")
                    else:
                        self.server_models[url] = model_name
                        logger.warning(f"Server {i} ({url}): no models found, using {model_name}")
                else:
                    logger.warning(f"Server {i} ({url}): status {r.status_code}")
                    self.server_models[url] = model_name
            except Exception as e:
                logger.warning(f"Server {i} ({url}): connection failed - {e}")
                self.server_models[url] = model_name

        logger.info(f"Initialized MultiServerVLLMGenerator with {self.num_servers} servers")

    def _get_session(self) -> requests.Session:
        """Get thread-local session."""
        if not hasattr(self._local, 'session'):
            self._local.session = requests.Session()
        return self._local.session

    def _get_server_for_query(self, query_index: int) -> Tuple[str, str]:
        """
        Deterministically assign a query to a server based on query index.

        Returns (server_url, model_name) tuple.
        """
        server_idx = query_index % self.num_servers
        server_url = self.server_urls[server_idx]
        model_name = self.server_models.get(server_url, self.model_name)
        return server_url, model_name

    def _build_prompt(self, query: ToolBenchQuery, tool_docs: str) -> str:
        """Build the prompt for tool-use generation."""
        system_prompt = """You are a helpful assistant that can use external tools/APIs to help users.

When you need to call a tool, output your reasoning followed by a function call in this format:
Thought: [your reasoning about which tool to use and why]
Action: [tool_name]
Action Input: {"param1": "value1", "param2": "value2"}

If you have gathered enough information, provide a final answer:
Thought: I now have enough information to answer.
Final Answer: [your response to the user]

Available Tools:
"""
        prompt = system_prompt + tool_docs + "\n\nUser Query: " + query.query
        return prompt

    def _format_for_chat(self, prompt: str) -> str:
        """Format prompt using chat template."""
        if self.tokenizer is None:
            return prompt

        messages = [{"role": "user", "content": prompt}]
        try:
            return self.tokenizer.apply_chat_template(
                messages,
                tokenize=False,
                add_generation_prompt=True,
            )
        except Exception:
            return prompt

    def generate_single(
        self,
        query_index: int,
        query: ToolBenchQuery,
        tool_docs: str,
        temperature: float = 0.0,
        max_tokens: int = 1024,
    ) -> Tuple[int, str]:
        """
        Generate a response for a single query.

        Returns (query_index, response) tuple for ordering.
        """
        server_url, model_name = self._get_server_for_query(query_index)

        prompt = self._build_prompt(query, tool_docs)
        formatted_prompt = self._format_for_chat(prompt)

        payload = {
            "model": model_name,
            "prompt": formatted_prompt,
            "max_tokens": max_tokens,
            "temperature": temperature if temperature > 0 else 0.01,
            "stop": ["<|im_end|>", "<|endoftext|>", "User Query:"],
        }

        # Add seed for determinism if specified
        if self.seed is not None:
            payload["seed"] = self.seed

        try:
            session = self._get_session()
            r = session.post(
                f"{server_url}/completions",
                json=payload,
                timeout=self.timeout,
            )
            r.raise_for_status()
            response = r.json()["choices"][0]["text"].strip()
            return (query_index, response)

        except Exception as e:
            logger.error(f"vLLM generation error on server {server_url}: {e}")
            return (query_index, f"# Generation error: {e}")

    def generate(
        self,
        query: ToolBenchQuery,
        tool_docs: str,
        temperature: float = 0.0,
        max_tokens: int = 1024,
    ) -> str:
        """Generate a response for a single query (uses first server)."""
        _, response = self.generate_single(0, query, tool_docs, temperature, max_tokens)
        return response


